// Логика микро-диалога: системный промпт, служебные пометки о ходе диалога и разбор ответа ИИ.

export const MAX_AI_TURNS = 4

const BASE_PROMPT = `Ты заботливый носитель вьетнамского языка. Ты ведешь короткий диалог (3-4 реплики) с новичком. Твои реплики должны быть короткими (1 предложение на вьетнамском), сопровождаться транскрипцией и переводом на русский. Если пользователь делает ошибку, не перебивай и отвечай по смыслу, но в конце дай мягкую подсказку 'Кстати, лучше сказать так: ...'`

export function buildSystemPrompt(situation) {
  return `${BASE_PROMPT}

Ситуация: ${situation.prompt}

Правила формата — отвечай ТОЛЬКО одним JSON-объектом, без markdown и пояснений:
{"vi": "...", "phonetic": "[...]", "ru": "...", "tip": null, "done": false}
- vi — одна короткая реплика на вьетнамском с полной диакритикой.
- phonetic — примерная транскрипция кириллицей в квадратных скобках.
- ru — перевод реплики полностью на русский, без вьетнамских слов.
- done — true только в твоей последней реплике диалога.
- tip — null во всех репликах, кроме последней. В последней: если пользователь ошибался — мягкая подсказка "Кстати, лучше сказать так: <правильная фраза> (<перевод>)"; если ошибок не было — одна короткая похвала по-русски.
- Пользователь — новичок: он может писать без диакритики, с ошибками или по-русски. Понимай по смыслу и продолжай сцену.`
}

// Служебная пометка для модели о номере реплики — в интерфейсе не показывается
export function turnNote(turn) {
  const finish = turn >= MAX_AI_TURNS ? ' Это последняя реплика: заверши диалог, поставь done: true и заполни tip.' : ''
  return `\n\n(Служебно: это твоя реплика ${turn} из ${MAX_AI_TURNS}.${finish})`
}

// Модель иногда оборачивает JSON в ```-блок или добавляет текст — достаём сам объект
export function parseReply(text) {
  const start = text.indexOf('{')
  const end = text.lastIndexOf('}')
  if (start !== -1 && end > start) {
    try {
      const data = JSON.parse(text.slice(start, end + 1))
      if (typeof data.vi === 'string') {
        return {
          vi: data.vi,
          phonetic: data.phonetic ?? '',
          ru: data.ru ?? '',
          tip: data.tip || null,
          done: Boolean(data.done),
        }
      }
    } catch {
      // упадём в запасной вариант ниже
    }
  }
  return { vi: text.trim(), phonetic: '', ru: '', tip: null, done: false }
}
